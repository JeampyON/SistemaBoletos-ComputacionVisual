    private void txtLectorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtLectorActionPerformed
        // 1. Capturar código y limpiarlo
        String codigo = txtLector.getText().trim().replace("*", "");
        
        if (codigo.isEmpty()) {
            return;
        }

        // 2. Validar con la base de datos (Consulta atómica)
        String respuesta = dao.validarEntradaEnPuerta(codigo);

        // 3. Cambiar color y emitir sonido según la respuesta
        if (respuesta.equals("APROBADO")) {
            pnlEstado.setBackground(new java.awt.Color(46, 204, 113)); // Verde
            lblResultado.setText("ACCESO APROBADO: " + codigo);
            java.awt.Toolkit.getDefaultToolkit().beep(); // Sonido nativo
        } else if (respuesta.equals("DUPLICADO")) {
            pnlEstado.setBackground(new java.awt.Color(243, 156, 18)); // Naranja
            lblResultado.setText("¡ALERTA! BOLETO YA USADO: " + codigo);
            java.awt.Toolkit.getDefaultToolkit().beep();
        } else {
            pnlEstado.setBackground(new java.awt.Color(231, 76, 60)); // Rojo
            lblResultado.setText("ACCESO DENEGADO - NO EXISTE: " + codigo);
            java.awt.Toolkit.getDefaultToolkit().beep();
        }

        // 4. Limpiar caja y devolver foco para la siguiente lectura
        txtLector.setText("");
        txtLector.requestFocus();
    }//GEN-LAST:event_txtLectorActionPerformed

