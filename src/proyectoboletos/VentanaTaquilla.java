    private void btnVenderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVenderActionPerformed
        int indice = cbxEventos.getSelectedIndex();
        if (indice == -1) return;

        Evento eventoElegido = listaEventos.get(indice);

        // Generamos un código numérico aleatorio corto basado en el tiempo
        String codigoGenerado = String.valueOf(System.currentTimeMillis()).substring(7);

        ultimoCodigoGenerado = codigoGenerado;
        // Si se vende con éxito (si hay aforo)
        if (dao.venderBoleta(eventoElegido.getIdEvento(), codigoGenerado)) {
            // Generamos la imagen del código de barras y la ponemos en el JLabel
            lblCodigoBarras.setIcon(Boleta.generarImagenCode39(codigoGenerado));
            // Actualizamos la tabla
            tblBoletas.setModel(dao.listarBoletas());
            javax.swing.JOptionPane.showMessageDialog(this, "Boleto generado con éxito.");
            cargarDatosIniciales(); // Vuelve a consultar la base de datos para refrescar el aforo
        }
    }//GEN-LAST:event_btnVenderActionPerformed

