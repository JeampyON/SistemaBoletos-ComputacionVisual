    private void cbxEventosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cbxEventosActionPerformed
        int indice = cbxEventos.getSelectedIndex();
        if (indice >= 0) {
            Evento eventoElegido = listaEventos.get(indice);
            lblAforo.setText("Aforo: " + eventoElegido.getBoletosVendidos() + " / " + eventoElegido.getAforoMaximo());
        }
    }//GEN-LAST:event_cbxEventosActionPerformed

    private void btnExportarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportarActionPerformed
        if (ultimoCodigoGenerado.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Primero debe vender un boleto.");
            return;
        }
        if (Boleta.guardarBoletoPNG(ultimoCodigoGenerado)) {
            javax.swing.JOptionPane.showMessageDialog(this, "¡Boleto exportado como boleto_" + ultimoCodigoGenerado + ".png!");
        }
    }//GEN-LAST:event_btnExportarActionPerformed

